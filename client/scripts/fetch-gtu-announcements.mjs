async function fetchHtml(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }
  return response.text();
}

function parseAnnouncementList(html) {
  const matches = [...html.matchAll(/<a href="(\/tr\/icerik\/9\/[^"]+?)">([\s\S]*?)<\/a>/g)];
  const seen = new Set();

  return matches
    .map((match) => {
      const href = match[1];
      const title = cleanText(match[2]);
      const id = href.match(/\/icerik\/9\/(\d+)\//)?.[1] || slugify(title);
      return {
        id: `gtu-general-${id}`,
        departmentId: 'gtu-genel',
        departmentName: 'GTU Genel Duyurular',
        title,
        dateText: 'GTU',
        detailUrl: `${BASE_URL}${href}`,
        sourceUrl: `${BASE_URL}${href}`,
        sourceHash: id,
        language: 'tr-TR',
        status: 'published',
      };
    })
    .filter((item) => {
      if (!item.title || seen.has(item.sourceUrl)) return false;
      seen.add(item.sourceUrl);
      return true;
    });
}

function parseDepartmentHomeAnnouncements(html, source) {
  const headingIndex = html.indexOf('>Duyurular<a');
  if (headingIndex === -1) return parseDepartmentListAnnouncements(html, source);

  const blockStart = html.indexOf('<div class="flex flex-col', headingIndex);
  const blockEnd = html.indexOf('</div></div></div>', blockStart);
  const block = html.slice(blockStart, blockEnd === -1 ? blockStart + 5000 : blockEnd);
  const itemPattern = /(?:<a href="([^"]+)"|<button\b)[\s\S]*?<div class="[^"]*(?:bg-\[#3a5189\]|text-white)[^"]*"[^>]*>([\s\S]*?)<\/div>\s*<p[^>]*>([\s\S]*?)<\/p>/g;
  const seen = new Set();

  const cardItems = [...block.matchAll(itemPattern)]
    .map((match, index) => {
      const rawHref = match[1] || '';
      const dateText = cleanText(match[2]) || 'GTU';
      const title = cleanText(match[3]);
      const sourceUrl = rawHref ? absoluteUrl(rawHref) : source.url;
      const idSource = `${source.departmentId}-${title}-${index}`;

      return {
        id: `gtu-${source.departmentId}-${slugify(idSource)}`,
        departmentId: source.departmentId,
        departmentName: source.departmentName,
        title,
        dateText,
        detailUrl: sourceUrl,
        sourceUrl,
        sourceHash: slugify(idSource),
        language: 'tr-TR',
        status: 'published',
        summary: sourceUrl.endsWith('.pdf')
          ? `${title}. Bu duyuru PDF dosyasina baglanir.`
          : `${title}. Bu duyuru icin kaynak sayfada ayri detay metni bulunamadi.`,
        bodyText: sourceUrl.endsWith('.pdf')
          ? title
          : `${title}. Bu duyuru icin kaynak sayfada ayri detay metni bulunamadi.`,
      };
    })
    .filter((item) => {
      if (!item.title || isIgnoredAnnouncementTitle(item.title) || seen.has(`${item.departmentId}-${item.title}`)) return false;
      seen.add(`${item.departmentId}-${item.title}`);
      return true;
    });

  return cardItems.length ? cardItems : parseDepartmentListAnnouncements(html, source);
}

function parseDepartmentListAnnouncements(html, source) {
  const headingIndex = html.search(/Duyurular/i);
  if (headingIndex === -1) return [];

  const block = html.slice(headingIndex, headingIndex + 18000);
  const matches = [...block.matchAll(/<a\s+href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g)];
  const seen = new Set();

  return matches
    .map((match, index) => {
      const rawHref = match[1] || '';
      const title = cleanText(match[2]);
      const sourceUrl = rawHref ? absoluteUrl(rawHref) : source.url;
      const idSource = `${source.departmentId}-${title}-${index}`;

      return {
        id: `gtu-${source.departmentId}-${slugify(idSource)}`,
        departmentId: source.departmentId,
        departmentName: source.departmentName,
        title,
        dateText: 'GTU',
        detailUrl: sourceUrl,
        sourceUrl,
        sourceHash: slugify(idSource),
        language: 'tr-TR',
        status: 'published',
        summary: sourceUrl.endsWith('.pdf')
          ? `${title}. Bu duyuru PDF dosyasina baglanir.`
          : `${title}. Bu duyuru icin kaynak sayfada ayri detay metni bulunamadi.`,
        bodyText: sourceUrl.endsWith('.pdf')
          ? title
          : `${title}. Bu duyuru icin kaynak sayfada ayri detay metni bulunamadi.`,
      };
    })
    .filter((item) => {
      const decodedUrl = decodeURIComponent(item.sourceUrl || '').toLocaleLowerCase('tr-TR');
      const isAnnouncementLink =
        decodedUrl.includes('/icerik/') ||
        decodedUrl.includes('/fileman/') ||
        decodedUrl.includes('.pdf');

      if (
        !item.title ||
        isIgnoredAnnouncementTitle(item.title) ||
        !isAnnouncementLink ||
        seen.has(`${item.departmentId}-${item.title}`)
      ) {
        return false;
      }
      seen.add(`${item.departmentId}-${item.title}`);
      return true;
    });
}

async function enrichDepartmentAnnouncement(item, source) {
  if (isPdfUrl(item.sourceUrl)) {
    try {
      const bodyText = await fetchPdfText(item.sourceUrl);
      if (!bodyText) return item;

      return {
        ...item,
        summary: summarize(bodyText),
        bodyText,
      };
    } catch (error) {
      console.warn(`PDF duyuru metni alinamadi: ${item.title} - ${error.message}`);
      return {
        ...item,
        summary: `${item.title}. PDF duyuru metni su anda okunamadi. Kaynak baglantisi: ${item.sourceUrl}`,
        bodyText: `${item.title}. PDF duyuru metni su anda okunamadi. Kaynak baglantisi: ${item.sourceUrl}`,
      };
    }
  }

  if (item.sourceUrl && item.sourceUrl !== source.url) {
    try {
      return await fetchAnnouncementDetail(item);
    } catch (error) {
      console.warn(`Bolum duyuru detayi alinamadi: ${item.title} - ${error.message}`);
    }
  }

  return item;
}

async function fetchAnnouncementDetail(item) {
  const detailResponse = await fetch(item.detailUrl);
  if (!detailResponse.ok) {
    throw new Error(`HTTP ${detailResponse.status}`);
  }

  const html = await detailResponse.text();
  const title = cleanText(
    firstMatch(html, /<h1[^>]*>([\s\S]*?)<\/h1>/) || item.title,
  );
  const richContent = firstMatch(html, /<div class="rich-text-content">([\s\S]*?)<\/div><div class="rounded-lg/) || '';
  const bodyText = cleanText(richContent);
  const summary = summarize(bodyText || title);

  return {
    ...item,
    title,
    summary,
    bodyText,
  };
}

async function fetchPdfText(url) {
  const response = await fetch(encodeURI(url));
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }

  const data = new Uint8Array(await response.arrayBuffer());
  const pdf = await pdfjsLib.getDocument({ data, disableWorker: true }).promise;
  const pageTexts = [];
  const maxPages = Math.min(pdf.numPages, 8);

  for (let pageNumber = 1; pageNumber <= maxPages; pageNumber += 1) {
    const page = await pdf.getPage(pageNumber);
    const content = await page.getTextContent();
    const pageText = cleanText(content.items.map((item) => item.str).join(' '));
    if (pageText) {
      pageTexts.push(`Sayfa ${pageNumber}. ${pageText}`);
    }
  }

  return pageTexts.join(' ').slice(0, 6000).trim();
}

function firstMatch(value, pattern) {
  return value.match(pattern)?.[1] || '';
}

function cleanText(value) {
  return decodeHtml(value)
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function decodeHtml(value) {
  return value
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rsquo;/g, "'")
    .replace(/&lsquo;/g, "'")
    .replace(/&rdquo;/g, '"')
    .replace(/&ldquo;/g, '"')
    .replace(/&ndash;/g, '-')
    .replace(/&mdash;/g, '-')
    .replace(/&bull;/g, '-')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>');
}

function absoluteUrl(value) {
  if (!value) return '';
  if (value.startsWith('http')) return value;
  return `${BASE_URL}${value.startsWith('/') ? value : `/${value}`}`;
}

function isPdfUrl(value) {
  return decodeURIComponent(value || '').toLocaleLowerCase('tr-TR').includes('.pdf');
}

function isIgnoredAnnouncementTitle(value) {
  const normalized = slugify(value);
  return [
    'ilan-portali',
    'kvkk-aydinlatma-metni',
    'iletisim',
    'contact',
    'jobs-portal',
    'use-of-personal-data',
  ].some((blocked) => normalized.includes(blocked));
}

function summarize(value) {
  if (value.length <= 260) return value;
  return `${value.slice(0, 260).trim()}...`;
}

function slugify(value) {
  return value
    .toLocaleLowerCase('tr-TR')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}
